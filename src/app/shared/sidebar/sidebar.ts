@Component({
  selector: 'app-sidebar',
  standalone: true,
  imports: [CommonModule, RouterLink, RouterLinkActive],
  templateUrl: './sidebar.html',
  styleUrl: './sidebar.css',
})
export class SidebarComponent implements OnInit, OnDestroy {
  @Input() items: SidebarEntry[] = [];
  @Input() user: SidebarUser = { name: 'User', email: '' };
  @Input() logoText = 'TRACI';

  private readonly sanitizer = inject(DomSanitizer);
  private readonly notifWs = inject(NotificationWebsocketService);  // <-- add
  private avatarSub!: Subscription;  // <-- add


  isCollapsed = signal(false);
  openMenus   = signal<Set<string>>(new Set());

  @HostBinding('class.collapsed')
get hostCollapsed(): boolean { return this.isCollapsed(); }

   ngOnInit(): void {  // <-- add
    this.notifWs.connect();
    this.avatarSub = this.notifWs.avatar$.subscribe((event: AvatarEvent) => {
      if (event.avatarUrl) {
        const fullUrl = event.avatarUrl.startsWith('http') ? event.avatarUrl : 'http://localhost:8080' + event.avatarUrl;
        this.user = { ...this.user, avatarUrl: fullUrl };
      }
    });
  }

  ngOnDestroy(): void {  // <-- add
    this.avatarSub?.unsubscribe();
  }

  toggle(): void {
    const collapsing = !this.isCollapsed();
    this.isCollapsed.set(collapsing);
    if (collapsing) this.openMenus.set(new Set());
  }

  toggleSubmenu(label: string): void {
    if (this.isCollapsed()) return;
    this.openMenus.update(prev => {
      const next = new Set(prev);
      next.has(label) ? next.delete(label) : next.add(label);
      return next;
    });
  }

  isSubmenuOpen(label: string): boolean { return this.openMenus().has(label); }
  isNavItem(entry: SidebarEntry): entry is SidebarNavItem { return !('divider' in entry); }
  isDivider(entry: SidebarEntry): entry is { divider: true } { return 'divider' in entry; }

  icon(name: string): SafeHtml {
    const path = ICONS[name] ?? ICONS['menu'];
    return this.sanitizer.bypassSecurityTrustHtml(
      `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" xmlns="http://www.w3.org/2000/svg">${path}</svg>`
    );
  }

  initials(): string {
    return this.user.name.split(' ').map(w => w[0] ?? '').join('').toUpperCase().slice(0, 2);
  }
}